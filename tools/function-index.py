#!/usr/bin/env python3
"""function-index.py -- model/FUNCTIONS.md: a map of js/quantum3d5.js, section by section.

The simulator's code is one long script in sections, each under a banner comment:
    // =====================================================================
    // SECTION NAME
    // =====================================================================
This lists every section, and every named function and class in it with its line, and the comment
line just above it when there is one. It is generated, never edited: run it after changing the code,
and tests/smoke.py's neighbour, `--check`, says when the map is stale.

usage:  python3 tools/function-index.py            write model/FUNCTIONS.md
        python3 tools/function-index.py --check    exit 1 if model/FUNCTIONS.md is out of date

Copyright (C) 2026 Corwin Brust, Bryant Frankford and Contributors.
SPDX-License-Identifier: GPL-3.0-or-later
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "js" / "quantum3d5.js"
OUT = ROOT / "model" / "FUNCTIONS.md"
BANNER = re.compile(r"^\s*// ?={5,}\s*$")
DEF = re.compile(r"^(\s*)(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(|^(\s*)class\s+([A-Za-z_$][\w$]*)")


def build():
    lines = SRC.read_text(encoding="utf-8").split("\n")
    out = ["# FUNCTIONS: a map of js/quantum3d5.js", "",
           "Generated by `tools/function-index.py` from the code; do not edit by hand. Line numbers are",
           "1-based. A name indented deeper than its neighbours is defined inside another function.", ""]
    section, count = "(before the first section)", 0
    rows = {section: []}
    order = [section]
    i = 0
    while i < len(lines):
        if BANNER.match(lines[i]) and i + 2 < len(lines) and BANNER.match(lines[i + 2]):
            section = re.sub(r"^\s*//\s?", "", lines[i + 1]).strip() or "(unnamed section)"
            if section not in rows:
                rows[section] = []; order.append(section)
            i += 3; continue
        m = DEF.match(lines[i])
        if m:
            name = m.group(2) or m.group(4)
            kind = "function" if m.group(2) else "class"
            prev = lines[i - 1].strip() if i else ""
            note = re.sub(r"^//\s?", "", prev) if prev.startswith("//") and not BANNER.match(lines[i - 1]) else ""
            rows[section].append((i + 1, kind, name, note.replace("|", "\\|")))
            count += 1
        i += 1
    out.append(f"{count} named functions and classes in {len(order)} sections.")
    out.append("")
    for s in order:
        if not rows[s]:
            continue
        out += [f"## {s}", "", "| line | name | the comment above it |", "|---:|---|---|"]
        out += [f"| {ln} | `{name}`{' (class)' if kind == 'class' else ''} | {note} |" for ln, kind, name, note in rows[s]]
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        ok = OUT.is_file() and OUT.read_text(encoding="utf-8") == text
        print("model/FUNCTIONS.md is " + ("current" if ok else "OUT OF DATE: run python3 tools/function-index.py"))
        sys.exit(0 if ok else 1)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
